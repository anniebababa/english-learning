export function getTodayPhrase(): Phrase {
  const start = new Date("2026-01-01").getTime();
  const today = new Date().getTime();
  const dayIndex = Math.floor((today - start) / (1000 * 60 * 60 * 24));
  return phrases[dayIndex % phrases.length];
}

export function getPhrasesByCategory(categoryId: string): Phrase[] {
  return phrases.filter((p) => p.category === categoryId);
}

export function groupBySubcategory(list: Phrase[]): Map<string, Phrase[]> {
  const map = new Map<string, Phrase[]>();
  for (const p of list) {
    const group = map.get(p.subcategory) ?? [];
    group.push(p);
    map.set(p.subcategory, group);
  }
  return map;
}
